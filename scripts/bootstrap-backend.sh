#!/usr/bin/env bash
# One-time bootstrap of the remote state backend (layer 00).
#
#   1. Apply 00-bootstrap with LOCAL state (the bucket doesn't exist yet).
#   2. Write live/<env>/backend.hcl from the outputs.
#   3. Migrate the 00-bootstrap state into the new bucket.
#   4. Fill in deployer_role_arn in common.tfvars.
#
# Run with admin credentials for the target account:
#   AWS_PROFILE=admin ./scripts/bootstrap-backend.sh lab
#
# Safe to re-run: if the state was already migrated it just runs a normal
# init + plan against the S3 backend.
set -Eeuo pipefail

ENV_NAME="${1:-lab}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_DIR="$ROOT/live/$ENV_NAME"
LAYER_DIR="$ENV_DIR/00-bootstrap"
BACKEND_HCL="$ENV_DIR/backend.hcl"
COMMON="$ENV_DIR/common.tfvars"

log() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
die() { printf '\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

command -v terraform >/dev/null || die "terraform not found"
command -v aws >/dev/null || die "aws cli not found"
[[ -d $LAYER_DIR ]] || die "no such layer: $LAYER_DIR"

ACCOUNT_ID="$(aws sts get-caller-identity --query Account --output text)"
CALLER="$(aws sts get-caller-identity --query Arn --output text)"
log "Account $ACCOUNT_ID as $CALLER"
read -r -p "Bootstrap state backend for '$ENV_NAME' in this account? [y/N] " ok
[[ $ok == [yY] ]] || exit 1

cd "$LAYER_DIR"

if [[ -f $BACKEND_HCL ]] && ! [[ -f terraform.tfstate ]]; then
  log "backend.hcl already exists: running a normal plan against S3"
  terraform init -backend-config="$BACKEND_HCL" -reconfigure
  terraform plan -var-file="$COMMON"
  exit 0
fi

# --- Phase 1: local state ---------------------------------------------------
log "Phase 1: apply with local state"
mv versions.tf versions.tf.bootstrap
# Same file without the backend block.
sed '/backend "s3" {/,/^  }/d' versions.tf.bootstrap > versions.tf
trap 'cd "$LAYER_DIR"; [[ -f versions.tf.bootstrap ]] && mv -f versions.tf.bootstrap versions.tf' EXIT

terraform init -reconfigure
terraform apply -var-file="$COMMON"

BUCKET="$(terraform output -raw state_bucket_name)"
KMS="$(terraform output -raw state_kms_key_arn)"
DEPLOYER="$(terraform output -raw deployer_role_arn)"
REGION="$(awk -F'"' '/^region/ {print $2}' "$COMMON")"

# --- Phase 2: backend.hcl -----------------------------------------------------
log "Phase 2: writing $BACKEND_HCL"
cat > "$BACKEND_HCL" <<EOF
# Generated by scripts/bootstrap-backend.sh. Commit this file; it holds no secrets.
bucket       = "$BUCKET"
region       = "$REGION"
encrypt      = true
kms_key_id   = "$KMS"
use_lockfile = true
EOF

# --- Phase 3: migrate -----------------------------------------------------------
log "Phase 3: migrating 00-bootstrap state into s3://$BUCKET"
mv -f versions.tf.bootstrap versions.tf
trap - EXIT
terraform init -backend-config="$BACKEND_HCL" -migrate-state -force-copy

# Only delete local state once the remote copy is confirmed readable.
terraform state list >/dev/null
rm -f terraform.tfstate terraform.tfstate.backup

# --- Phase 4: common.tfvars -------------------------------------------------------
log "Phase 4: setting deployer_role_arn in common.tfvars"
sed -i.bak -E "s#^deployer_role_arn *=.*#deployer_role_arn = \"$DEPLOYER\"#" "$COMMON" && rm -f "$COMMON.bak"

log "Done. Next:"
cat <<EOF
  - Commit live/$ENV_NAME/backend.hcl and live/$ENV_NAME/common.tfvars
  - GitHub > Settings > Environments > ami-build > variable PACKER_ROLE_ARN = $(terraform output -raw github_packer_role_arn)
  - Follow docs/atlantis-github.md, then apply live/$ENV_NAME/05-atlantis locally.
EOF
